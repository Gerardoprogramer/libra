import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { compileFunction } from "node:vm";

import * as orm from "drizzle-orm";
import * as pg from "drizzle-orm/pg-core";
import type { SelectedFields } from "drizzle-orm/pg-core/query-builders/select.types";
import { drizzle } from "drizzle-orm/pg-proxy";
import ts from "typescript";

import * as schema from "../schema";
import * as selection from "../../lib/edition-selection";
import { isPublicEditionStatus } from "../../lib/editorial-status";
import * as visibility from "./editorial-visibility";

type Row = Record<string, unknown>;
type Statement = { sql: string; params: unknown[] };

// Load the real query functions with an in-memory Drizzle driver and no Next cache.
// Neither src/db/index.ts nor a PostgreSQL connection is ever loaded. SQL is still
// generated by Drizzle; fixture rows stand in for the results returned by the DB.
const loadQueries = compileFunction(
  ts.transpileModule(readFileSync(new URL("./books.ts", import.meta.url), "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText,
  ["require", "exports"],
);

function queriesWithRows(...responses: Row[][]) {
  const statements: Statement[] = [];
  const db = {
    select(fields: SelectedFields) {
      return drizzle(async (sql, params) => {
        assert.match(sql, /^select /i);
        statements.push({ sql, params });
        const rows = responses.shift();
        assert.ok(rows, "Unexpected query: no fixture response remains");
        return {
          rows: rows.map((row) =>
            Object.keys(fields).map((key) => {
              assert.ok(Object.hasOwn(row, key), `Missing fixture field ${key}`);
              return row[key] instanceof Date ? row[key].toISOString() : row[key];
            }),
          ),
        };
      }).select(fields);
    },
  };
  const dependencies: Record<string, unknown> = {
    "server-only": {},
    "next/cache": { cacheLife() {}, cacheTag() {} },
    "@/db": { db },
    "drizzle-orm": orm,
    "drizzle-orm/pg-core": pg,
    "@/db/schema": schema,
    "@/lib/edition-selection": selection,
    "./editorial-visibility": visibility,
  };
  const queries = {} as typeof import("./books");
  loadQueries((id: string) => {
    assert.ok(Object.hasOwn(dependencies, id), `Unexpected query dependency: ${id}`);
    return dependencies[id];
  }, queries);
  return { queries, statements, assertConsumed: () => assert.equal(responses.length, 0) };
}

function assertPublicFilter({ sql, params }: Statement) {
  assert.match(sql, /where .*"editions"\."publication_status" = \$\d+/);
  assert.match(sql, /"editions"\."copyright_status" in \(/);
  for (const status of ["PUBLISHED", "PUBLIC_DOMAIN_VERIFIED", "LICENSED", "ORIGINAL"]) {
    assert.ok(params.includes(status));
  }
  assert.ok(!params.some((value) => ["DRAFT", "PENDING_REVIEW", "REJECTED"].includes(String(value))));
}

function edition(slug: string, language: string, overrides: Row = {}) {
  return {
    id: slug,
    slug,
    language,
    isPreferred: false,
    createdAt: new Date("2020-01-01"),
    title: slug,
    description: null,
    translator: null,
    publicationYear: null,
    coverUrl: null,
    sourceName: null,
    sourceIdentifier: null,
    sourceUrl: null,
    publicationStatus: "PUBLISHED",
    copyrightStatus: "PUBLIC_DOMAIN_VERIFIED",
    ...overrides,
  };
}

const book = {
  id: "book-1",
  slug: "one-work",
  originalTitle: "Original work",
  originalLanguage: "en",
  originalPublicationYear: 1897,
};
const author = {
  id: "author-1",
  slug: "one-author",
  name: "One Author",
  position: 0,
  birthYear: null,
  deathYear: null,
};
const category = {
  categoryId: "classic",
  categorySlug: "classics",
  categoryName: "Clásicos",
  fallbackCategoryName: "Classics",
  categoryPosition: 0,
};

function joinedRow(candidate: ReturnType<typeof edition>, overrides: Row = {}) {
  return {
    bookId: book.id,
    bookSlug: book.slug,
    originalTitle: book.originalTitle,
    publicationYear: book.originalPublicationYear,
    authorId: author.id,
    authorName: author.name,
    authorPosition: author.position,
    editionId: candidate.id,
    editionSlug: candidate.slug,
    editionTitle: candidate.title,
    editionLanguage: candidate.language,
    editionIsPreferred: candidate.isPreferred,
    editionCreatedAt: candidate.createdAt,
    editionCoverUrl: candidate.coverUrl,
    ...category,
    ...overrides,
  };
}

const english = edition("english", "en");
const spanish = edition("spanish", "es");
const preferred = edition("spanish-preferred", "es", { isPreferred: true });
const draft = edition("spanish-draft", "es", { publicationStatus: "DRAFT", isPreferred: true });

test("an explicit edition resumes that edition irrespective of interface locale and editorial preference", async () => {
  const h = queriesWithRows([book], [author], [english, spanish, preferred], [], []);
  const selected = await h.queries.getBookBySlug(book.slug, "es", english.id);
  assert.equal(selected?.edition.id, english.id);
  assertPublicFilter(h.statements[2]);
  assert.ok(h.statements.at(-1)?.params.includes(english.id));
  h.assertConsumed();
});

test("an unavailable edition ID never falls back to another edition's chapters", async () => {
  const h = queriesWithRows([book], [author], [english]);
  assert.equal(await h.queries.getBookBySlug(book.slug, "en", "private-or-other-book"), null);
  assertPublicFilter(h.statements[2]);
  h.assertConsumed();
});
const cases = [
  { name: "A: a public Spanish edition", editions: [english, spanish], expected: "spanish" },
  { name: "B: English fallback", editions: [english], expected: "english" },
  {
    name: "C: several Spanish editions with an editorial preference",
    editions: [spanish, preferred, english],
    expected: "spanish-preferred",
  },
  { name: "D: only a Spanish draft", editions: [draft], expected: null },
  { name: "E: English published and Spanish draft", editions: [english, draft], expected: "english" },
  {
    name: "F: Spanish translations without a preference",
    editions: [edition("translation-z", "es"), edition("translation-a", "es"), english],
    expected: "translation-a",
  },
  {
    name: "rejected and pending translations do not override the fallback",
    editions: [
      english,
      edition("rejected", "es", { copyrightStatus: "REJECTED", isPreferred: true }),
      edition("pending", "es", { copyrightStatus: "PENDING_REVIEW", isPreferred: true }),
    ],
    expected: "english",
  },
];

for (const scenario of cases) {
  test(`public catalog, author bibliography and book detail agree — ${scenario.name}`, async () => {
    // Simulate SQL-filtered results, and independently assert that every real
    // edition query includes the public status predicates and allowed values.
    const publicEditions = scenario.editions.filter((item) =>
      isPublicEditionStatus(item.publicationStatus, item.copyrightStatus),
    );
    const rows = publicEditions.map((item) => joinedRow(item));
    const catalog = queriesWithRows(rows);
    const authorPage = queriesWithRows([author], rows);
    const detail = queriesWithRows([book], [author], publicEditions, ...(publicEditions.length ? [[], []] : []));

    const books = await catalog.queries.getBooks("es");
    const bibliography = await authorPage.queries.getAuthorBySlug(author.slug, "es");
    const selected = await detail.queries.getBookBySlug(book.slug, "es");

    assert.equal(books.length, scenario.expected ? 1 : 0);
    assert.equal(books[0]?.title ?? null, scenario.expected);
    assert.equal(bibliography?.books.length ?? 0, scenario.expected ? 1 : 0);
    assert.equal(bibliography?.books[0]?.title ?? null, scenario.expected);
    assert.equal(selected?.edition.slug ?? null, scenario.expected);
    if (selected) {
      assert.equal(books[0].language, selected.edition.language);
      assert.equal(books[0].slug, book.slug);
      assert.equal(bibliography?.books[0].slug, book.slug);
      assert.ok(detail.statements.at(-1)?.params.includes(selected.edition.id));
    }
    assertPublicFilter(catalog.statements[0]);
    assertPublicFilter(authorPage.statements[1]);
    assertPublicFilter(detail.statements[2]);
    for (const harness of [catalog, authorPage, detail]) harness.assertConsumed();
  });
}

test("multiple editions, authors and categories produce one catalog card per work", async () => {
  const rows = [english, spanish, preferred].flatMap((item) =>
    [0, 1].flatMap((authorPosition) =>
      [0, 1].map((categoryPosition) =>
        joinedRow(item, {
          authorId: `author-${authorPosition}`,
          authorName: `Author ${authorPosition}`,
          authorPosition,
          categoryId: `category-${categoryPosition}`,
          categorySlug: `category-${categoryPosition}`,
          categoryName: `Category ${categoryPosition}`,
          categoryPosition,
        }),
      ),
    ),
  );
  for (const locale of ["es", "en"] as const) {
    const { queries, statements } = queriesWithRows([...rows].reverse());
    const result = await queries.getBooks(locale, { category: "category-1" });
    assert.equal(result.length, 1);
    assert.equal(result[0].title, locale === "es" ? preferred.title : english.title);
    assert.equal(result[0].author, "Author 0, Author 1");
    assert.deepEqual(
      result[0].categories.map((item) => item.slug),
      ["category-0", "category-1"],
    );
    assertPublicFilter(statements[0]);
    assert.match(statements[0].sql, /exists \(select/);
    assert.ok(statements[0].params.includes("category-1"));
  }
});

test("search matches another public edition but displays the edition selected for the locale", async () => {
  const rows = [english, spanish].map((item) =>
    joinedRow(item, {
      editionTitle: item.slug === "english" ? "Dracula" : "Drácula",
    }),
  );

  const { queries, statements } = queriesWithRows(rows);

  const result = await queries.getBooks("es", {
    query: "Dracula",
  });

  assert.equal(result.length, 1);
  assert.equal(result[0].slug, book.slug);
  assert.equal(result[0].title, "Drácula");
  assert.equal(result[0].language, "es");

  assertPublicFilter(statements[0]);

  assert.ok(statements[0].params.includes("%Dracula%"));
  assert.match(statements[0].sql, /"books"\."original_title"/);
  assert.match(statements[0].sql, /"authors"\."name"/);
  assert.match(statements[0].sql, /exists \(select/);
  assert.match(statements[0].sql, /"editions"\."title" ilike/);

  // Searching an English edition must not force the English edition
  // when the requested UI locale is Spanish.
  assert.notEqual(result[0].title, "Dracula");

  assert.equal(statements.length, 1);
});

test("search query requires public edition visibility", async () => {
  const { queries, statements } = queriesWithRows([]);

  const result = await queries.getBooks("es", {
    query: "Drácula",
  });

  assert.equal(result.length, 0);

  assertPublicFilter(statements[0]);

  assert.ok(statements[0].params.includes("%Drácula%"));

  // The edition-title search is performed inside an EXISTS subquery.
  // That subquery must also contain the public editorial visibility filter.
  const publicationStatusMatches = statements[0].sql.match(/"editions"\."publication_status" = \$\d+/g);

  const copyrightStatusMatches = statements[0].sql.match(/"editions"\."copyright_status" in \(/g);

  assert.ok(publicationStatusMatches && publicationStatusMatches.length >= 2);
  assert.ok(copyrightStatusMatches && copyrightStatusMatches.length >= 2);

  assert.equal(statements.length, 1);
});

test("an author bibliography deduplicates editions and categories while preserving distinct books", async () => {
  const rows = [english, spanish, preferred].flatMap((item) => [joinedRow(item), joinedRow(item)]);
  rows.push(joinedRow(english, { bookId: "book-2", bookSlug: "another-work" }));
  const { queries } = queriesWithRows([author], rows);
  const result = await queries.getAuthorBySlug(author.slug, "es");
  assert.deepEqual(
    result?.books.map((item) => item.slug),
    ["one-work", "another-work"],
  );
  assert.deepEqual(
    result?.books.map((item) => item.language),
    ["es", "en"],
  );
  assert.deepEqual(
    result?.books.map((item) => item.categories.length),
    [1, 1],
  );
});

test("category counts use unique Books across editions and locale translations", async () => {
  const rows = ["book-1", "book-1", "book-1", "book-2"].flatMap((bookId) => [
    { categoryId: "classic", categorySlug: "classics", translationLocale: "es", translationName: "Clásicos", bookId },
    { categoryId: "classic", categorySlug: "classics", translationLocale: "en", translationName: "Classics", bookId },
  ]);
  for (const locale of ["es", "en"] as const) {
    const { queries, statements } = queriesWithRows(rows);
    assert.deepEqual(await queries.getCategories(locale), [
      { id: "classic", slug: "classics", name: locale === "es" ? "Clásicos" : "Classics", bookCount: 2 },
    ]);
    assertPublicFilter(statements[0]);
  }
});

test("the author listing counts distinct public Books in SQL, not joined editions", async () => {
  const { queries, statements } = queriesWithRows([{ ...author, bookCount: 2 }]);
  const result = await queries.getAuthors();
  assert.equal(result[0].bookCount, 2);
  assert.match(statements[0].sql, /count\(distinct "books"\."id"\)/);
  assert.match(statements[0].sql, /group by "authors"\."id"/);
  assertPublicFilter(statements[0]);
});

test("authors and categories without public books do not appear in listings", async () => {
  const { queries, statements } = queriesWithRows([], []);
  assert.deepEqual(await queries.getAuthors(), []);
  assert.deepEqual(await queries.getCategories("es"), []);
  statements.forEach(assertPublicFilter);
});
